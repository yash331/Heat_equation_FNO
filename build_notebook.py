                "class SpectralConv1d(nn.Module):\n",
                "    \"\"\"1D Fourier Spectral Convolution Layer.\"\"\"\n",
                "    def __init__(self, in_channels: int, out_channels: int, modes: int):\n",
                "        super().__init__()\n",
                "        self.in_channels = in_channels\n",
                "        self.out_channels = out_channels\n",
                "        self.modes = modes\n",
                "\n",
                "        # Learnable complex weights for positive Fourier modes\n",
                "        scale = 1.0 / (in_channels * out_channels)\n",
                "        self.weights = nn.Parameter(\n",
                "            scale * torch.randn(in_channels, out_channels, modes, dtype=torch.cfloat)\n",
                "        )\n",
                "\n",
                "    def forward(self, x: torch.Tensor) -> torch.Tensor:\n",
                "        batch_size, _, length = x.shape\n",
                "\n",
                "        # 1. Real FFT along spatial dimension\n",
                "        x_ft = torch.fft.rfft(x, dim=-1)\n",
                "\n",
                "        # 2. Multiply retained modes with complex weight tensor\n",
                "        num_modes = min(self.modes, x_ft.shape[-1])\n",
                "        out_ft = torch.zeros(\n",
                "            batch_size, self.out_channels, x_ft.shape[-1],\n",
                "            device=x.device, dtype=torch.cfloat\n",
                "        )\n",
                "        out_ft[:, :, :num_modes] = torch.einsum(\n",
                "            \"bix,iox->box\",\n",
                "            x_ft[:, :, :num_modes],\n",
                "            self.weights[:, :, :num_modes]\n",
                "        )\n",
                "\n",
                "        # 3. Inverse Real FFT\n",
                "        return torch.fft.irfft(out_ft, n=length, dim=-1)\n",
                "\n",
                "\n",
                "class FNO1d(nn.Module):\n",
                "    \"\"\"1D Fourier Neural Operator.\"\"\"\n",
                "    def __init__(self, modes: int = 16, width: int = 64, in_channels: int = 3, out_channels: int = 1, num_layers: int = 4):\n",
                "        super().__init__()\n",
                "        self.modes = modes\n",
                "        self.width = width\n",
                "        self.num_layers = num_layers\n",
                "\n",
                "        # 1. Lifting Layer: maps [u0(x), x, theta] -> width\n",
                "        self.lifting = nn.Linear(in_channels, width)\n",
                "\n",
                "        # 2. Fourier Layers: Spectral Convolution + 1x1 Conv residual\n",
                "        self.spectral_convs = nn.ModuleList([\n",
                "            SpectralConv1d(width, width, modes) for _ in range(num_layers)\n",
                "        ])\n",
                "        self.residual_convs = nn.ModuleList([\n",
                "            nn.Conv1d(width, width, kernel_size=1) for _ in range(num_layers)\n",
                "        ])\n",
                "\n",
                "        # 3. Projection Layer: width -> 128 -> 1\n",
                "        self.projection1 = nn.Linear(width, 128)\n",
                "        self.projection2 = nn.Linear(128, out_channels)\n",
                "\n",
                "    def forward(self, x: torch.Tensor) -> torch.Tensor:\n",
                "        # Lifting\n",
                "        x = self.lifting(x)\n",
                "        x = x.permute(0, 2, 1)  # (batch, width, spatial_res)\n",
                "\n",
                "        # Fourier Operator Layers\n",
                "        for i in range(self.num_layers):\n",
                "            x1 = self.spectral_convs[i](x)\n",
                "            x2 = self.residual_convs[i](x)\n",
                "            x = F.gelu(x1 + x2)\n",
                "\n",
                "        # Projection\n",
                "        x = x.permute(0, 2, 1)  # (batch, spatial_res, width)\n",
                "        x = self.projection1(x)\n",
                "        x = F.gelu(x)\n",
                "        return self.projection2(x) # (batch, spatial_res, out_channels)\n",
                "\n",
